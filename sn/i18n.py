STRINGS = {"en": EN, "hi": HI, "kn": KN}


def t(lang, key, p=None):
    """Translate key into lang (falls back to English), filling {placeholders}.

    A placeholder value may itself be {"key": ..., "p": ...}; it is translated first.
    """
    s = STRINGS.get(lang, EN).get(key) or EN.get(key, key)
    for k, v in (p or {}).items():
        if isinstance(v, dict) and "key" in v:
            v = t(lang, v["key"], v.get("p"))
        s = s.replace("{" + k + "}", str(v))
    return s


def missing():
    """Keys that a language lacks (used by the self-check)."""
    return {lang: sorted(set(EN) - set(tbl)) for lang, tbl in STRINGS.items() if lang != "en"}
